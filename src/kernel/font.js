// Our own single-stroke font, in the style of technical drawing lettering
// (ISO 3098): every glyph is a few centre lines, drawn with a round pen.
// Units: capital height 10, lowercase x-height 7, descenders to -3, baseline
// 0. Each glyph has an advance width w (the pen's thickness and the gap
// between letters are added when setting text) and strokes [[x, y], ...].

const DEG = Math.PI / 180;
// Points along an ellipse arc from a0 to a1 degrees (either direction).
function arc(cx, cy, rx, ry, a0, a1) {
  const n = Math.max(2, Math.ceil(Math.abs(a1 - a0) / 12));
  return Array.from({ length: n + 1 }, (_, i) => {
    const a = (a0 + ((a1 - a0) * i) / n) * DEG;
    return [cx + rx * Math.cos(a), cy + ry * Math.sin(a)];
  });
}
// A stroke from pieces: points and arcs, joined end to end.
const P = (...pieces) => pieces.flatMap((p) => (typeof p[0] === "number" ? [p] : p));
const ring = (cx, cy, rx, ry = rx) => arc(cx, cy, rx, ry, 0, 360);
const dot = (x, y) => [[x, y], [x, y + 0.01]];
const g = (w, ...strokes) => ({ w, s: strokes });

const bowl = (x0, rx = 3, ry = 3.5) => ring(x0 + rx, ry, rx, ry); // a lowercase round bowl, x-height tall

