// Lays out text as strokes. size: capital height (mm); pen: stroke width
// (mm). Returns { strokes, box: [x0, y0, x1, y1] } with the first line's
// baseline at y = 0 and the text starting at x = 0 (align "left"), centred
// on x = 0 ("center") or ending there ("right"). Lines are split at "\n".
export function layoutText(str, size, { pen, align = "left", spacing = 1, lineHeight = 1.6 } = {}) {
  const k = size / 10;
  const penU = pen / k;
  const gap = (2.2 + penU) * spacing;
  const strokes = [];
  let x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity;
  str.split("\n").forEach((line, li) => {
    const chars = [...line];
    const missing = chars.filter((ch) => !GLYPHS[ch]);
    if (missing.length) throw new Error(`text has characters the font does not have: ${[...new Set(missing)].map((c) => JSON.stringify(c)).join(", ")}`);
    let width = 0;
    chars.forEach((ch, i) => (width += GLYPHS[ch].w + (i < chars.length - 1 ? gap : 0)));
    let x = align === "center" ? -width / 2 : align === "right" ? -width : 0;
    const y = -li * 10 * lineHeight;
    for (const ch of chars) {
      for (const s of GLYPHS[ch].s) {
        const pts = s.map(([px, py]) => [(x + px) * k, (y + py) * k]);
        strokes.push(pts);
        for (const [px, py] of pts) (x0 = Math.min(x0, px)), (y0 = Math.min(y0, py)), (x1 = Math.max(x1, px)), (y1 = Math.max(y1, py));
      }
      x += GLYPHS[ch].w + gap;
    }
  });
  return { strokes, box: [x0 - pen / 2, y0 - pen / 2, x1 + pen / 2, y1 + pen / 2] };
}
